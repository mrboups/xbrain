"""Parser for Claude Code session files (``~/.claude/projects/<slug>/<uuid>.jsonl``).

The file is JSONL: one JSON object per line, appended as the session runs.
Lines are heterogeneous — user turns, assistant turns, tool calls, tool
results, summaries, file-history snapshots, meta records — and only a subset
of them is conversation.

What is kept:
  * ``type == "user"`` whose ``message.content`` is a string, or a list
    containing ``text`` blocks. A user record whose content is entirely
    ``tool_result`` blocks is the RUNTIME replying to the model, not a person
    speaking; it is dropped.
  * ``type == "assistant"``, keeping only the ``text`` blocks of
    ``message.content``. ``tool_use`` and ``thinking`` blocks are dropped.

What is dropped, and why:
  * ``summary`` / ``system`` / ``file-history-snapshot`` / anything else — not
    speech (the ``summary`` record's text is reused as the title instead).
  * ``isMeta: true`` — Claude Code's own bookkeeping records.
  * ``isSidechain: true`` — sub-agent transcripts. They belong to a tool
    invocation, not to the conversation the person had.
  * slash-command scaffolding (``<command-name>``, ``<local-command-stdout>``,
    ``<system-reminder>``) — injected markup, never typed by anyone.

A truncated final line is the NORMAL case, not the exception: copying the file
while the session is live cuts the last record mid-write. Every line is decoded
independently and a failure skips only that line.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any

from app.services.transcript_import.types import (
    MAX_TURNS_PER_CONVERSATION,
    ParsedConversation,
    TranscriptParseError,
    clean_source_id,
    clean_text,
    make_turn,
)

FORMAT = "claude-code"

# Records that are structurally not conversation, whatever else they carry.
_NON_SPEECH_TYPES = frozenset(
    {
        "summary",
        "system",
        "file-history-snapshot",
        "progress",
        "attachment",
    }
)

# Markup Claude Code injects into a "user" record that no person typed.
_INJECTED_PREFIXES = (
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<system-reminder>",
    "Caveat: The messages below were generated by the user while running",
)

_TITLE_MAX_CHARS = 120


def _parse_ts(value: Any) -> datetime | None:
    """Best-effort ISO-8601 → aware datetime. Never raises."""
    if not isinstance(value, str) or not value:
        return None
    text = value.strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    try:
        dt = datetime.fromisoformat(text)
    except (ValueError, TypeError):
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt


def _is_injected(text: str) -> bool:
    return any(text.startswith(prefix) for prefix in _INJECTED_PREFIXES)


def _text_from_content(content: Any, *, role: str) -> str:
    """Extract the speech from a Claude Code ``message.content`` value.

    A string is speech as-is. A list is a block sequence: keep ``text`` blocks,
    drop everything else (``tool_use``, ``tool_result``, ``thinking``,
    ``image``, ``redacted_thinking``, and any block type invented later —
    the allow-list is deliberately closed).
    """
    if isinstance(content, str):
        return clean_text(content)
    if not isinstance(content, list):
        return ""

    pieces: list[str] = []
    for block in content:
        if not isinstance(block, dict):
            continue
        if block.get("type") != "text":
            continue
        piece = clean_text(block.get("text"))
        if piece:
            pieces.append(piece)
    if not pieces:
        return ""
    # A user record carrying only tool_result blocks yields no pieces above and
    # is therefore already dropped — which is the intent.
    del role
    return clean_text("\n\n".join(pieces))


def _iter_records(raw: str):
    """Yield one decoded object per line, skipping anything undecodable.

    Skipping is the whole point: the last line of a live session is routinely
    half-written, and a JSONL file that has been through a copy/paste round
    trip can carry blank or wrapped lines anywhere.
    """
    for line in raw.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        try:
            record = json.loads(stripped)
        except (ValueError, TypeError):
            continue
        if isinstance(record, dict):
            yield record


def parse(raw: str) -> list[ParsedConversation]:
    """Parse a Claude Code JSONL session file.

    Returns one :class:`ParsedConversation` per ``sessionId`` found (a single
    file is normally one session; a concatenation of files is not, and grouping
    keeps those apart so each dedupes on its own identity).

    Raises:
        TranscriptParseError: when not a single line of the input decodes as a
            JSON object — i.e. this is not a JSONL file at all.
    """
    if not isinstance(raw, str) or not raw.strip():
        raise TranscriptParseError(
            "The file is empty. Export a Claude Code session file "
            "(~/.claude/projects/<project>/<session>.jsonl) and try again."
        )

    # session_id -> conversation. ``None`` groups records that carry no
    # sessionId at all (older files) into a single anonymous conversation.
    conversations: dict[str | None, ParsedConversation] = {}
    titles: dict[str | None, str] = {}
    saw_any_record = False

    for record in _iter_records(raw):
        saw_any_record = True
        rec_type = record.get("type")
        session_id = clean_source_id(record.get("sessionId"))

        if rec_type == "summary":
            # Not speech, but Claude Code's own name for the session — the best
            # title available. Keyed by leafUuid, which we cannot resolve to a
            # session cheaply, so the first summary wins for the whole file.
            summary = clean_text(record.get("summary"))
            if summary and None not in titles:
                titles[None] = summary[:_TITLE_MAX_CHARS]
            continue

        if rec_type in _NON_SPEECH_TYPES or rec_type not in ("user", "assistant"):
            continue
        if record.get("isMeta") is True or record.get("isSidechain") is True:
            continue

        message = record.get("message")
        if not isinstance(message, dict):
            continue
        role = message.get("role") or rec_type
        text = _text_from_content(message.get("content"), role=str(role))
        if not text or _is_injected(text):
            continue

        turn = make_turn(role, text, _parse_ts(record.get("timestamp")))
        if turn is None:
            continue

        conv = conversations.get(session_id)
        if conv is None:
            conv = ParsedConversation(source_id=session_id, started_at=turn.timestamp)
            conversations[session_id] = conv
        if conv.turn_count >= MAX_TURNS_PER_CONVERSATION:
            continue
        conv.turns.append(turn)

    if not saw_any_record:
        raise TranscriptParseError(
            "No JSON records could be read from this file. A Claude Code "
            "session is a .jsonl file with one JSON object per line."
        )

    result: list[ParsedConversation] = []
    fallback_title = titles.get(None)
    for conv in conversations.values():
        if not conv.turns:
            continue
        conv.title = fallback_title or _title_from_turns(conv)
        result.append(conv)
    return result


def _title_from_turns(conv: ParsedConversation) -> str | None:
    for turn in conv.turns:
        if turn.role == "user":
            first_line = turn.content.strip().splitlines()[0] if turn.content.strip() else ""
            if first_line:
                return first_line[:_TITLE_MAX_CHARS]
    return None
